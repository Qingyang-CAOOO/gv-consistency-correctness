from __future__ import annotations

import torch
from torch import Tensor


def weighted_mean_loss(per_example_loss: Tensor, frozen_weights: Tensor, *, eps: float = 1e-12) -> Tensor:
    """Weighted average loss for soft GV fine-tuning.

    The weights are detached deliberately: they should be generated by the
    previous/frozen model theta_old, then used to optimize theta_new.
    """
    if per_example_loss.shape != frozen_weights.shape:
        raise ValueError("per_example_loss and frozen_weights must have identical shapes")
    if torch.any(frozen_weights < 0):
        raise ValueError("weights must be nonnegative")

    w = frozen_weights.detach()
    denom = w.sum().clamp_min(eps)
    return torch.sum(w * per_example_loss) / denom
